#!/usr/bin/env node
// Regenerates web/src/mock/files.js: a snapshot of this repository's file list used by
// mock mode (?mock=1). Run from anywhere: `node web/tests/tools/gen-mock-files.mjs`.
import { execFileSync } from 'node:child_process';
import { statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const out = join(root, 'web/src/mock/files.js');
const SKIP = [/^target\//, /^bench-repos\//, /^\.ferro\//, /node_modules\//, /^apps\/desktop\/src-tauri\/gen\//, /^web\/src\/mock\/files\.js$/];

const list = execFileSync('git', ['-C', root, 'ls-files', '-co', '--exclude-standard'], { encoding: 'utf8' })
  .split('\n')
  .filter(Boolean)
  .filter((p) => !SKIP.some((re) => re.test(p)))
  .sort();

const rows = [];
for (const p of list) {
  try {
    rows.push([p, statSync(join(root, p)).size]);
  } catch {
    /* deleted in worktree */
  }
}
const body = `// Generated by web/tests/tools/gen-mock-files.mjs — do not edit by hand.\n// Snapshot of the repository file list for mock mode.\nexport const FILES = ${JSON.stringify(rows)};\n`;
writeFileSync(out, body);
console.log(`wrote ${rows.length} files to ${out}`);
